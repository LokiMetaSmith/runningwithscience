import os
import subprocess
import pytest
from bs4 import BeautifulSoup

SITE_DIR = "_site"

@pytest.fixture(scope="session", autouse=True)
def build_jekyll():
    """Build the Jekyll site before running tests."""
    subprocess.run(["bundle", "exec", "jekyll", "build"], check=True)
    assert os.path.exists(SITE_DIR), "Jekyll site did not build."

def get_soup(filepath):
    with open(os.path.join(SITE_DIR, filepath), "r") as f:
        return BeautifulSoup(f, "html5lib")

def test_about_page_hcard():
    """Test that the about page contains the h-card microformat."""
    soup = get_soup("about.html")
    hcard = soup.find(class_="h-card")
    assert hcard is not None, "h-card not found on about page"

    p_name = hcard.find(class_="p-name")
    assert p_name is not None, "p-name missing in h-card"

    p_note = hcard.find(class_="p-note")
    assert p_note is not None, "p-note missing in h-card"

def test_home_page_hfeed():
    """Test that the homepage contains the h-feed microformat and rel='me' links."""
    soup = get_soup("index.html")

    hfeed = soup.find(class_="h-feed")
    assert hfeed is not None, "h-feed not found on homepage"

    hentries = hfeed.find_all(class_="h-entry")
    assert len(hentries) > 0, "No h-entry posts found in h-feed on homepage"

    for entry in hentries:
        assert entry.find(class_="p-name") is not None, "p-name missing in h-entry"
        assert entry.find(class_="dt-published") is not None, "dt-published missing in h-entry"
        assert entry.find(class_="u-url") is not None, "u-url missing in h-entry"

        author_card = entry.find(class_="p-author h-card")
        assert author_card is not None, "p-author h-card missing in h-entry"
        assert author_card.find(class_="p-name") is not None, "p-name missing in p-author h-card"

def test_post_page_hentry():
    """Test that individual post pages contain the h-entry microformat."""
    # Find a post in the generated site
    post_dir = os.path.join(SITE_DIR, "2025", "06", "02")
    if os.path.exists(post_dir):
        post_file = os.path.join(post_dir, "The-IoT-Light-Switch-Rule.html")
        assert os.path.exists(post_file), f"Expected post file not found: {post_file}"

        with open(post_file, "r") as f:
            soup = BeautifulSoup(f, "html5lib")

        hentry = soup.find(class_="h-entry")
        assert hentry is not None, "h-entry not found on post page"
        assert hentry.find(class_="p-name") is not None, "p-name missing in post h-entry"
        assert hentry.find(class_="e-content") is not None, "e-content missing in post h-entry"

        author_card = hentry.find(class_="p-author h-card")
        assert author_card is not None, "p-author h-card missing in post h-entry"
        assert author_card.find(class_="p-name") is not None, "p-name missing in post p-author h-card"
    else:
        pytest.fail("Could not find a generated post page to test.")

def test_rel_me_links():
    """Test that the default layout includes rel='me' links."""
    soup = get_soup("index.html")
    rel_me_links = soup.find_all(rel="me")
    assert len(rel_me_links) >= 3, "Expected at least 3 rel='me' links (YouTube, Business, Email) across layout and page content"

def test_rss_feed_generated():
    """Test that the RSS feed is generated by the jekyll-feed plugin."""
    feed_path = os.path.join(SITE_DIR, "feed.xml")
    assert os.path.exists(feed_path), "feed.xml was not generated"

    with open(feed_path, "r") as f:
        content = f.read()
        assert "<feed" in content or "<rss" in content, "feed.xml does not look like an RSS/Atom feed"

def test_404_page_generated():
    """Test that the 404 page is generated and contains default layout elements."""
    page_path = os.path.join(SITE_DIR, "404.html")
    assert os.path.exists(page_path), "404.html was not generated"

    soup = get_soup("404.html")

    # Verify it uses the default layout (checking for rel='me' links)
    rel_me_links = soup.find_all(rel="me")
    assert len(rel_me_links) >= 3, "Expected at least 3 rel='me' links on 404 page (from layout)"

    # Verify content
    content_div = soup.find(class_="container")
    assert content_div is not None, "Container div missing on 404 page"
    assert "404" in content_div.text, "404 text missing from 404 page content"
